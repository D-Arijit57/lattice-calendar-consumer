import {readFileSync} from 'node:fs';
import {build} from 'esbuild';
import {describe, expect, it} from 'vitest';

// The Vercel functions are committed build output. If server code changes without re-running
// `npm run bundle:api`, production would silently run old code; this fails instead.
describe('api/*.js Vercel bundles', () => {
  it.each(['events', 'types'])('api/%s.js is up to date and self-contained', async (name) => {
    const {outputFiles} = await build({
      entryPoints: ['server/vercel-entry.ts'], bundle: true, platform: 'node', format: 'esm', target: 'node20',
      banner: {js: '// GENERATED by `npm run bundle:api` from server/vercel-entry.ts. Do not edit.'},
      write: false, outfile: `api/${name}.js`,
    });
    const committed = readFileSync(`api/${name}.js`, 'utf8');
    expect(committed).toBe(outputFiles[0].text);
    expect(committed).not.toMatch(/from\s+["']\.{1,2}\//); // no relative imports left to resolve at runtime
  });
});
