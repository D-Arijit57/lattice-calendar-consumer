// Bundles server/vercel-entry.ts into self-contained ESM files under api/ (the Vercel Functions).
// The output is committed so a deploy works even if the platform snapshots api/ before the build runs.
import {build} from 'esbuild';

for (const name of ['events', 'types']) {
  await build({
    entryPoints: ['server/vercel-entry.ts'],
    outfile: `api/${name}.js`,
    bundle: true,
    platform: 'node',
    format: 'esm',
    target: 'node20',
    banner: {js: '// GENERATED by `npm run bundle:api` from server/vercel-entry.ts. Do not edit.'},
  });
}
console.log('bundled api/events.js, api/types.js');
